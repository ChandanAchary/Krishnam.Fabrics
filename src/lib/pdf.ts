import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { fmtMonthYear } from './date';
import { fmtCurrency, getCurrencySymbol } from './money';
import type { MonthlySalary, Labourer } from '@/types/database';
import { format } from 'date-fns';

interface SalaryRowForPdf {
  salary: MonthlySalary;
  labourer: Pick<Labourer, 'name' | 'phone' | 'designation'>;
}

export function generateSalaryPDF(opts: {
  companyName: string;
  month: number;
  year: number;
  generatedBy: string;
  rows: SalaryRowForPdf[];
}) {
  const { companyName, month, year, generatedBy, rows } = opts;
  const doc = new jsPDF({ orientation: 'landscape', unit: 'pt', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();

  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text(companyName, 40, 40);

  doc.setFontSize(12);
  doc.setFont('helvetica', 'normal');
  doc.text(`Monthly Salary Report — ${fmtMonthYear(month, year)}`, 40, 60);

  doc.setFontSize(9);
  doc.setTextColor(120);
  doc.text(`Generated by ${generatedBy} on ${format(new Date(), 'dd-MMM-yyyy HH:mm')}`, 40, 76);
  doc.setTextColor(0);

  const totals = rows.reduce(
    (acc, r) => {
      acc.daysPresent += r.salary.days_present;
      acc.halfDays += r.salary.half_days_count;
      acc.gross += Number(r.salary.calculated_salary);
      acc.advance += Number(r.salary.advance_deducted);
      acc.net += Number(r.salary.net_salary);
      if (r.salary.payment_status === 'not_paid') acc.unpaid += Number(r.salary.net_salary);
      return acc;
    },
    { daysPresent: 0, halfDays: 0, gross: 0, advance: 0, net: 0, unpaid: 0 }
  );

  const sym = getCurrencySymbol();

  autoTable(doc, {
    startY: 96,
    head: [[
      '#', 'Labourer', 'Designation', 'Present', 'Half', `Wage (${sym})`,
      `Gross (${sym})`, `Advance (${sym})`, `Net (${sym})`, 'Status', 'Paid On',
    ]],
    body: rows.map((r, i) => [
      i + 1,
      r.labourer.name,
      r.labourer.designation ?? '—',
      r.salary.days_present,
      r.salary.half_days_count,
      Number(r.salary.daily_wage_used).toFixed(2),
      Number(r.salary.calculated_salary).toFixed(2),
      Number(r.salary.advance_deducted).toFixed(2),
      Number(r.salary.net_salary).toFixed(2),
      r.salary.payment_status === 'paid' ? 'Paid' : 'Not Paid',
      r.salary.paid_on ? format(new Date(r.salary.paid_on), 'dd-MMM-yyyy') : '—',
    ]),
    foot: [[
      { content: 'TOTAL', colSpan: 3, styles: { halign: 'right', fontStyle: 'bold' } },
      totals.daysPresent,
      totals.halfDays,
      '',
      { content: totals.gross.toFixed(2), styles: { fontStyle: 'bold' } },
      { content: totals.advance.toFixed(2), styles: { fontStyle: 'bold' } },
      { content: totals.net.toFixed(2), styles: { fontStyle: 'bold' } },
      { content: `Unpaid: ${sym}${totals.unpaid.toFixed(2)}`, colSpan: 2, styles: { halign: 'right', textColor: [220, 38, 38] } },
    ]],
    styles: { fontSize: 8, cellPadding: 3 },
    headStyles: { fillColor: [30, 74, 245], textColor: 255 },
    footStyles: { fillColor: [241, 245, 249], textColor: 30 },
    columnStyles: {
      0: { halign: 'right', cellWidth: 24 },
      3: { halign: 'right' },
      4: { halign: 'right' },
      5: { halign: 'right' },
      6: { halign: 'right' },
      7: { halign: 'right' },
      8: { halign: 'right' },
    },
  });

  // Footer page numbers
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(150);
    doc.text(`Page ${i} of ${pageCount}`, pageWidth - 80, doc.internal.pageSize.getHeight() - 20);
  }

  const filename = `Krishnam_Salary_${format(new Date(year, month - 1, 1), 'MMM')}_${year}.pdf`;
  doc.save(filename);
  void fmtCurrency;
}
